def _full_body(t): return t[1:-1] if len(t) >= 2 and t[0] == '𝍁' and t[-1] == '𝍁' else None

def _stack(blocks):
    "Combine MCP reply blocks in order, keeping `𝍁…𝍁` around the combined text if any text block is marked full."
    out = [dict(b) for b in blocks]
    for b in out[:-1]:
        if (t := b.get('text')) and not t.endswith('\n'): b['text'] = t + '\n'
    if any((t := b.get('text')) is not None and _full_body(t.rstrip('\n')) is not None for b in out):
        parts, rest = [], []
        for b in out:
            if (t := b.get('text')) is None: rest.append(b)
            else:
                body = t.rstrip('\n')
                inner = _full_body(body)
                parts.append((body if inner is None else inner) + t[len(body):])
        return [dict(type='text', text='𝍁' + ''.join(parts) + '𝍁'), *rest]
    return out

def _is_no_current(res):
    r = res.get('result') if res else None
    return bool(r and r.get('isError') and 'no current kernel' in ''.join(b.get('text', '') for b in r.get('content', [])))

