@patch
def _cap_text(self:Router, content, agent, note=''):
    "Cap text blocks in `content` (plus optional `note`) to `self.maxout` UTF-8 bytes, saving overflow for `%cont`."
    note_blk = [dict(type='text', text=note)] if note else []
    if not self.maxout: return note_blk + content
    joined = ''.join(b.get('text', '') for b in content if b['type'] == 'text')
    note_bytes = len(note.encode('utf-8')) + 1 if note else 0
    if len(joined.encode('utf-8')) + note_bytes <= self.maxout: return note_blk + content
    full = joined.startswith('𝍁') and joined.endswith('𝍁') and len(joined) >= 2
    data = (joined[1:-1] if full else joined).encode('utf-8')
    if self._tmpdir is None: self._tmpdir = tempfile.TemporaryDirectory(prefix='clikernel-')
    self._out_seq += 1
    oid = str(self._out_seq)
    path = Path(self._tmpdir.name)/f'out_{oid}.txt'
    path.write_bytes(data)
    total = len(data)
    mk_foot = lambda rem: f'\n[truncated: {rem:,} of {total:,} bytes left; full output: {path}; %cont or %cont {oid} for next]'
    chunk, offset = _page(data, 0, self.maxout - note_bytes, mk_foot, full=full)
    if offset < total:
        self._conts.setdefault(agent, {})[oid] = (path, offset, full, total)
        self._last[agent] = oid
    return note_blk + [dict(type='text', text=chunk)] + [b for b in content if b['type'] != 'text']

