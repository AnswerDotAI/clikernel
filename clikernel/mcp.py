@patch
async def aclose(self:Router):
    "Close all sessions and their autoclose kernels, remove any temporary output directory, then stop any owned gateway."
    if self._reaper and not self._reaper.done():
        self._reaper.cancel()
        with suppress(asyncio.CancelledError): await self._reaper
    sessions = list(self.sessions.values())
    self.sessions.clear()
    try: results = await asyncio.gather(*(s.aclose() for s in sessions), return_exceptions=True)
    finally:
        if self.child:
            self.child.stop()
            self.child = None
        if self._tmpdir:
            self._tmpdir.cleanup()
            self._tmpdir = None
    errors = [r for r in results if isinstance(r, BaseException)]
    if errors: raise BaseExceptionGroup('MCP session cleanup failed', errors)

