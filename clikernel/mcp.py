def _cut_utf8(b, budget, snap=256):
    "Byte index <= `budget` in UTF-8 bytes `b` on a char boundary, snapping back to a nearby newline."
    end = min(budget, len(b))
    while end > 0 and end < len(b) and (b[end] & 0xC0) == 0x80: end -= 1
    if end == 0 and b:
        end = 1
        while end < len(b) and (b[end] & 0xC0) == 0x80: end += 1
    elif end < len(b):
        nl = b.rfind(b'\n', max(end // 2, end - snap), end)
        if nl >= 0: end = nl + 1
    return end

def _page(data, offset, budget, mk_footer, full=False):
    "Return `(text, new_offset)` fitting `data[offset:]` plus footer and `𝍁…𝍁` wrapper within `budget` UTF-8 bytes."
    wrap = 8 if full else 0
    tail = data[offset:]
    if len(tail) + wrap <= budget:
        body = tail.decode('utf-8')
        return (f'𝍁{body}𝍁' if full else body), len(data)
    avail = budget - wrap - len(mk_footer(len(tail)).encode('utf-8'))
    end = _cut_utf8(tail, max(1, avail))
    body = tail[:end].decode('utf-8') + mk_footer(len(tail) - end)
    return (f'𝍁{body}𝍁' if full else body), offset + end

