@patch
async def dispatch(self:Router, msg, requester=None):
    "Answer initialization and ping locally. Forward tool calls to gateways."
    method,id = msg.get('method'), msg.get('id')
    try:
        if method == 'initialize':
            info = (await self.session()).info
            return jresp(id, dict(protocolVersion=msg['params'].get('protocolVersion', '2025-06-18'), capabilities=dict(tools={}),
                serverInfo=dict(name='clikernel', version=__version__), instructions=info.get('instructions')))
        if id is None:
            if method == 'notifications/cancelled' and (s := self.inflight.get(msg['params'].get('requestId'))) is not None:
                await s.tr.send(msg)
            return None
        if method == 'ping': return jresp(id, {})
        if method == 'tools/list': return jresp(id, dict(tools=await self.tools()))
        if method == 'tools/call':
            args = msg['params'].setdefault('arguments', {})
            agent = args.pop('agent', None) or None
            tool = msg['params']['name']
            if tool == 'exec' and (m := _CONT_RE.match(args.get('code', '').strip())): return jresp(id, self._cont(agent, m.group(1)))
            fired = scan(args.get('code', '')) if tool == 'exec' else []
            if blocks := [r.note for r in fired if r.block]:
                return jresp(id, dict(isError=True, content=[dict(type='text', text=' '.join(blocks)+' (If the block seems wrong here, tell your user.)')]))
            has_host = 'host' in args
            host = args.pop('host', '') or ''
            h = host if has_host else self.cur.setdefault(agent, self.cur.get(None, ''))
            if h or os.environ.get('CLIKERNEL_HOST'): args.pop('cwd', None)
            cwd = args.pop('cwd', None) if tool == 'exec' else None
            gen = self._agent_gen.get((h, agent), 0) if agent is not None else 0
            try:
                s, res = await self._send(h, agent, msg)
                if agent is not None and tool == 'exec' and _is_no_current(res):
                    opened = await self._ensure_agent_kernel(h, agent, s, cwd, gen)
                    if isinstance(opened, dict): res = jresp(id, opened)
                    elif opened is not None:
                        _, res = await self._send(h, agent, msg)
                        if opened and res and 'result' in res and not res['result'].get('isError'):
                            res['result']['content'] = _stack(opened + res['result']['content'])
            finally: self.inflight.pop(id, None)
            if res and 'result' in res:
                if has_host and tool in ('use_kernel', 'create') and not res['result'].get('isError'):
                    self.cur[agent] = host
                content = _cap_images(res['result']['content'])
                note = ''.join(f'<note>\n{r.note}\n</note>\n' for r in fired) if fired and not self.quiet else ''
                res['result']['content'] = self._cap_text(content, agent, note=note)
            return res
        return jerr(id, -32601, f'method not found: {method}')
    except Exception as e: return None if id is None else jerr(id, -32603, str(e))

