@patch
async def _parent_kernel(self:Router, h):
    s = self.sessions.get((h, None))
    if not s: return None
    try: r = await s.call('list_kernels')
    except httpx.HTTPStatusError as e:
        if e.response.status_code != 404: raise
        self.sessions.pop((h, None), None)
        return None
    if r.get('isError'): return None
    txt = ''.join(b.get('text', '') for b in r.get('content', []) if b.get('type') == 'text')
    for line in txt.splitlines():
        if line.endswith('<- current') and (m := re.search(r'\bkernel=(\S+)', line)): return m.group(1)
    return None

@patch
async def _ensure_agent_kernel(self:Router, h, agent, s, cwd, gen):
    key = (h, agent)
    async with self._agent_locks.setdefault(key, asyncio.Lock()):
        if self._agent_gen.get(key, 0) != gen: return []
        impl = await self._parent_kernel(h)
        if not impl: return None
        kw = dict(kernel=impl)
        if cwd: kw['cwd'] = cwd
