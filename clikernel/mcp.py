@patch
def _cont(self:Router, agent, oid=None):
    "Return the next chunk of a truncated reply for `agent`, optionally selecting `oid`."
    aconts = self._conts.get(agent) or {}
    key = oid or self._last.get(agent)
    if not key or key not in aconts:
        msg = f'No pending output with id {oid}.' if oid else 'No pending output to continue.'
        return dict(isError=True, content=[dict(type='text', text=msg)])
    path, offset, full, total = aconts[key]
    data = path.read_bytes()
    mk_foot = lambda rem: f'\n[{rem:,} of {total:,} bytes left; %cont or %cont {key} for next]'
    chunk, new_offset = _page(data, offset, self.maxout, mk_foot, full=full)
    if new_offset >= total:
        aconts.pop(key, None)
        if self._last.get(agent) == key: self._last.pop(agent, None)
    else:
        aconts[key] = (path, new_offset, full, total)
        self._last[agent] = key
    return dict(content=[dict(type='text', text=chunk)])

